make_xy_surface <- function(model, raw_data, ref_vars, ylab_hormone, panel_title,
                             term_name = "s(x_proj,y_proj)") {
  grid <- expand.grid(
    x_proj = seq(min(raw_data$x_proj, na.rm = TRUE),
                 max(raw_data$x_proj, na.rm = TRUE), length.out = 60),
    y_proj = seq(min(raw_data$y_proj, na.rm = TRUE),
                 max(raw_data$y_proj, na.rm = TRUE), length.out = 60)
  )
  for (v in names(ref_vars)) grid[[v]] <- ref_vars[[v]]

  pred <- predict(model, newdata = grid, type = "terms", terms = term_name)
  grid$partial_effect <- as.numeric(pred[, 1])

  ggplot(grid, aes(x_proj, y_proj, fill = partial_effect)) +
    geom_raster() +
    geom_contour(aes(z = partial_effect), colour = "white", linewidth = 0.25, alpha = 0.6) +
