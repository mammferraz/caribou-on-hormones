message("\n── Supplementary Figure 7: Road effects (all-season + winter) ──")

infile_roads  <- "MNR_Road_Segments.geojson"
infile_lookup <- "winter_roads_all2.csv"
infile_open   <- "Roads_open.csv"

# Winter roads from the provincial layer (00b_road_layers.R): the old
# MNR_Road_Segments.geojson held only 541 of 968 Winter segments.
roads_sf <- road_layer("winter") |> janitor::clean_names()

road_lookup <- read_csv(infile_lookup, show_col_types = FALSE) |> janitor::clean_names()
roads_open  <- read_csv(infile_open,   show_col_types = FALSE) |> janitor::clean_names()
roads_named <- roads_sf |> left_join(road_lookup, by = "ogf_id")
# Spatial-smooth coordinates are held in EPSG:4326 (degrees) — what every
# s(x, y) term in this project has always used. Stated explicitly rather
# than inherited from a road layer's CRS, so swapping road layers can never
# silently re-project the smooths. Road DISTANCES are separate, in metres.
SPATIAL_SMOOTH_CRS <- 4326


dat_sf_road <- dat_map |>
  st_as_sf(coords = c("longitude", "latitude"), crs = 4326)

dat_sf_road$dist_road_km <- nearest_road_km(dat_sf_road, roads_named)

# NOTE: (pcid, date) is NOT a unique row key — 18 individuals were
# sampled twice on the same day (repeat pellets), so a many-to-many
# join on (pcid, date) alone silently cross-products those rows,
# inflating n. Adding tz_sample_number makes the key unique per row
# (same fix as 04_climate_road_analyses.R).
dat_roads <- dat_sf_road |>
  st_drop_geometry() |>
  select(pcid, date, tz_sample_number, dist_road_km) |>
  right_join(dat, by = c("pcid", "date", "tz_sample_number"), relationship = "one-to-one") |>
  left_join(
    roads_open |>
      group_by(year) |>
      summarise(days_open = max(days_open, na.rm = TRUE), .groups = "drop"),
    by = "year"
  ) |>
  mutate(survey = factor(survey), year_f = factor(year),
         preg_group = factor(preg_group,
                              levels = c("Male","Female_nonpregnant","Female_pregnant"))) |>
  filter(!is.na(dist_road_km)) |>
  # Road distance is log-transformed (pre-computed column, not an inline
  # transform — inline s(log(dist_road_km)) breaks gratia::smooth_estimates()'s
  # name matching, same issue already hit with pop_density in 09). k reduced
  # from 8 to 5 to match the corrected spec confirmed in 03_winter_road_analyses.R
  # and 04_climate_road_analyses.R (raw dist_road_km with k=8 was overfitting a
  # right-skewed distance measure).
  mutate(log_dist_road_km = log(dist_road_km))

dat_road_cort <- dat_roads |> filter(is.finite(cortisol))
dat_road_t3   <- dat_roads |> filter(is.finite(t3), t3 > 0)

# PROJECT DECISION: for landscape covariates, the s(x, y)-augmented
# model is reported as the PRIMARY model, regardless of BIC (see
# 03_winter_road_analyses.R Part 2E). Attach projected coordinates so
# this figure model matches the primary model in 03_winter_road_analyses.R.
dat_road_cort <- dat_road_cort |>
  bind_cols(st_coordinates(st_transform(
    st_as_sf(dat_road_cort, coords = c("longitude", "latitude"), crs = 4326),
    SPATIAL_SMOOTH_CRS
  )) |> as.data.frame() |> rename(x_proj = X, y_proj = Y))
dat_road_t3 <- dat_road_t3 |>
  bind_cols(st_coordinates(st_transform(
    st_as_sf(dat_road_t3, coords = c("longitude", "latitude"), crs = 4326),
    SPATIAL_SMOOTH_CRS
  )) |> as.data.frame() |> rename(x_proj = X, y_proj = Y))

# NOTE: days_open was previously included here as a parametric term, which
# made these figure models differ slightly from the PRIMARY winter-road
# models reported in the manuscript Results (fit in 03_winter_road_analyses.R
# Part 2E, which do NOT include days_open). That produced a figure whose
# panels could not be reconciled with the edf/F/p values quoted in the text
# (e.g. FT3 p = 0.0106 here vs p = 0.0016 reported). days_open is dropped so
# panels (c-d) reproduce the reported model exactly. Road-season length is
# still analysed separately in 03 as its own year-level covariate.
# julian k = 5 also matches 03's spec.
m_road_cort <- gam(cortisol ~ s(survey, bs = "re") + year_f + preg_group +
                     s(log_dist_road_km, k = 5, bs = "tp") +
                     s(julian, k = 5, bs = "tp") +
                     s(x_proj, y_proj, bs = "tp", k = 30),
                   data = dat_road_cort, family = Gamma(link = "log"), method = "REML")
m_road_t3   <- gam(t3 ~ s(survey, bs = "re") + year_f + preg_group +
                     s(log_dist_road_km, k = 5, bs = "tp") +
                     s(julian, k = 5, bs = "tp") +
                     s(x_proj, y_proj, bs = "tp", k = 30),
                   data = dat_road_t3, family = Gamma(link = "log"), method = "REML")

sm_road_cort <- smooth_df(m_road_cort, "s(log_dist_road_km)")
sm_road_t3   <- smooth_df(m_road_t3,   "s(log_dist_road_km)")

message("Winter road GAM summaries:")
print(summary(m_road_cort)$s.table)
print(summary(m_road_t3)$s.table)

