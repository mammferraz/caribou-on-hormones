# NOTE: road distance uses log_dist_road_km (pre-computed column), matching
# the additive/tensor model specs above and 03/04's corrected fix.
make_te_surface <- function(model, raw_data, ylab_hormone, snow_col = "snow_lag5") {
  grid <- expand.grid(
    snow        = seq(min(raw_data[[snow_col]], na.rm = TRUE),
                       max(raw_data[[snow_col]], na.rm = TRUE), length.out = 60),
    log_dist_road_km = seq(min(raw_data$log_dist_road_km, na.rm = TRUE),
                            max(raw_data$log_dist_road_km, na.rm = TRUE), length.out = 60)
  )
  names(grid)[names(grid) == "snow"] <- snow_col
  # predict.gam() needs every model variable present in newdata, even
  # when we only want the te() term's contribution via type = "terms" —
  # mgcv still builds the full model matrix. Add placeholder reference
  # values for the other terms (their actual values don't matter here
  # since we only extract the tensor term below).
  grid$survey     <- factor(raw_data$survey[1],     levels = levels(raw_data$survey))
  grid$year_f     <- factor(raw_data$year_f[1],     levels = levels(raw_data$year_f))
  grid$preg_group <- factor(raw_data$preg_group[1], levels = levels(raw_data$preg_group))
  grid$julian     <- median(raw_data$julian, na.rm = TRUE)
  # model now also includes s(x_proj, y_proj) (project decision — spatial
  # term is part of the primary model); hold at reference (median) values
  # since we only extract the te(snow, road) term below.
  grid$x_proj     <- median(raw_data$x_proj, na.rm = TRUE)
  grid$y_proj     <- median(raw_data$y_proj, na.rm = TRUE)

  lag_days <- if (snow_col == "snow_lag2") "2" else "5"
  te_term  <- paste0("te(", snow_col, ",log_dist_road_km)")

  pred <- predict(model, newdata = grid, type = "terms",
                   terms = te_term)
  grid$partial_effect <- as.numeric(pred[, 1])

  ggplot(grid, aes(.data[[snow_col]], log_dist_road_km, fill = partial_effect)) +
    geom_raster() +
    geom_contour(aes(z = partial_effect), colour = "white", linewidth = 0.25, alpha = 0.6) +
    geom_point(data = raw_data, aes(.data[[snow_col]], log_dist_road_km),
               inherit.aes = FALSE, size = 0.3, alpha = 0.25, colour = "black") +
    scale_fill_viridis_c(name = paste0("Partial effect\non log(", ylab_hormone, ")"), option = "magma") +
    labs(x = paste0(lag_days, "-day snow-on-ground (cm)"), y = "log(distance to nearest road, km)") +
    theme_ms
}

