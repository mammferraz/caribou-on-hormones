infile_climate <- "climatedaily_all_surveys.csv"

clim_all <- read_csv(infile_climate, show_col_types = FALSE) |>
  janitor::clean_names() |>
  mutate(date = as.Date(local_date), local_year = as.integer(local_year),
         month = month(date))

clim_winter <- clim_all |> filter(month %in% c(1, 2, 3))

sample_survey_dates <- dat |>
  filter(!is.na(date), !is.na(climate_group)) |>
  distinct(pcid, year, date, climate_group)

clim_winter_split <- split(clim_winter, clim_winter$climate_group)

calc_lag_mean <- function(target_date, clim_df, lag_start, lag_end) {
  clim_df |>
    filter(date <  target_date - lubridate::days(lag_start - 1),
           date >= target_date - lubridate::days(lag_end)) |>
    summarise(across(where(is.numeric), ~ mean(.x, na.rm = TRUE)))
}

climate_lags <- sample_survey_dates |>
  rowwise() |>
  mutate(short  = list(calc_lag_mean(date, clim_winter_split[[climate_group]], 1, 5)),
         short2 = list(calc_lag_mean(date, clim_winter_split[[climate_group]], 1, 2))) |>
  ungroup() |>
  unnest(short, names_sep = "_") |>
  unnest(short2, names_sep = "_")

clim_lag_clean <- climate_lags |>
  select(pcid, year, date, short_min_temperature, short_snow_on_ground,
         short2_min_temperature, short2_snow_on_ground) |>
  rename(min_lag5 = short_min_temperature, snow_lag5 = short_snow_on_ground,
         min_lag2 = short2_min_temperature, snow_lag2 = short2_snow_on_ground)

dat_clim <- dat |>
  left_join(clim_lag_clean, by = c("pcid", "year", "date")) |>
  mutate(survey = factor(survey), year_f = factor(year),
         preg_group = factor(preg_group,
                              levels = c("Male","Female_nonpregnant","Female_pregnant")))

# ---- Null and climate models --------------------------------
# FCM uses the 2-day short-lag climate columns; FT3 keeps the 5-day
# columns (see 02_climate_analyses.R header for rationale).

dat_cort_base  <- dat_clim |> filter(is.finite(cortisol), !is.na(julian))
dat_cort_clim  <- dat_cort_base |> filter(is.finite(min_lag2), is.finite(snow_lag2))
dat_t3_base    <- dat_clim |> filter(is.finite(t3), t3 > 0, !is.na(julian))
dat_t3_clim    <- dat_t3_base |> filter(is.finite(min_lag5), is.finite(snow_lag5))

m_cort_null <- gam(cortisol ~ s(survey, bs = "re") + year_f + preg_group +
                     s(julian, bs = "cc", k = 12),
                   data = dat_cort_clim, family = Gamma(link = "log"), method = "REML")
m_cort_clim <- gam(cortisol ~ s(survey, bs = "re") + year_f + preg_group +
                     s(min_lag2, k = 6) + s(snow_lag2, k = 4) +
                     s(julian, bs = "cc", k = 12),
                   data = dat_cort_clim, family = Gamma(link = "log"), method = "REML")

m_t3_null   <- gam(t3 ~ s(survey, bs = "re") + year_f + preg_group +
                     s(julian, bs = "cc", k = 12),
                   data = dat_t3_clim, family = Gamma(link = "log"), method = "REML")
# FT3's "with climate" model uses the combined (snow + temperature)
# model, matching the primary/reported FT3 climate model in
# 02_climate_analyses.R. UPDATED — after reducing snow's k from 8 to 4,
# the combined model now has the clearly lower/better AIC (12317.83 vs
# 12368.42 for snow-only, ΔAIC ≈ 50.6), and snow alone is no longer
# significant on its own (p = 0.555), so the combined model replaces
# snow-only here too, matching FCM's model (m_cort_clim, also combined).
m_t3_clim   <- gam(t3 ~ s(survey, bs = "re") + year_f + preg_group +
                     s(min_lag5, k = 4) + s(snow_lag5, k = 4) +
                     s(julian, bs = "cc", k = 12),
                   data = dat_t3_clim, family = Gamma(link = "log"), method = "REML")

extract_re <- function(model, label) {
  sm <- smooth_estimates(model, smooth = "s(survey)") |> add_confint()
  sm$model <- label
  sm
}

