# NOTE: both hormones' combined models use snow_on_ground + dist_road_km
# (NOT temperature) — matching 04_climate_road_analyses.R exactly, which
# is what the manuscript Results text (Task 8) reports. An earlier
# version of this section plotted FT3 against temperature instead of
# snow, which did not match the analysis actually reported in the
# manuscript; that mismatch is fixed here.
# FCM's snow term uses the 2-day short-lag window (snow_lag2); FT3 keeps
# the 5-day window (snow_lag5) — see 02_climate_analyses.R header.

dat_joint <- dat_roads |>
